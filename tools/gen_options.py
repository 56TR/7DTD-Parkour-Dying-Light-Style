# Writes Config/XUi_Menu/windows.xml (the Options > General > Parkour tab) and Config/Localization.csv from
# tools/i18n/strings.json (every player-facing text, all languages). V3.2 reads only Localization.csv from a mod.
# Row order and keys must match PkSettings.Defs in src/Game/PkSettings.cs (tools/i18n/check.py verifies it).
#   python -I tools/gen_options.py <mod root>
import csv
import io
import json
import os
import sys

root = sys.argv[1]
data = json.load(open(os.path.join(root, 'tools', 'i18n', 'strings.json'), encoding='utf-8'))
langs = data['languages']
entries = data['entries']

# options rows: every label entry xuiPk<Key>
keys = [e['key'][len('xuiPk'):] for e in entries if e['kind'] == 'label']

buf = io.StringIO()
w = csv.writer(buf, lineterminator='\n')
w.writerow(['Key', 'File', 'Type', 'UsedInMainMenu', 'NoTranslate'] + langs)
for e in entries:
    menu = 'x' if e['kind'] in ('tab', 'label', 'tooltip') else ''
    kind = 'Options Menu' if menu else 'Perk'
    w.writerow([e['key'], 'UI' if menu else 'progression', kind, menu, ''] + [e.get(l, '') for l in langs])
os.makedirs(os.path.join(root, 'Config'), exist_ok=True)
with open(os.path.join(root, 'Config', 'Localization.csv'), 'w', encoding='utf-8-sig', newline='') as f:
    f.write(buf.getvalue())

CTRL = 'ParkourMovement.OptionEntryParkour, ParkourMovement'
combos = '\n'.join(
    f'\t\t\t\t\t\t<options_combo name_localization_prefix="xuiPk" name="{key}" option_controller="{CTRL}" prefname="{key}" '
    f'type="ComboBoxBool" localization_prefix="xuiComboOnOff" value_wrap="false" width="1150" />'
    for key in keys)
xml = f'''<configs>
\t<!-- Parkour Movement: Options > General > Parkour (generated by tools/gen_options.py) -->
\t<append xpath="/windows/window[@name='optionsGeneral']/rect[@name='tabs']/rect[@name='content']/rect[@name='tabsContents']">
\t\t<rect controller="TabSelectorTab" tab_key="xuiOptionsGeneralParkour">
\t\t\t<rect name="scrollarea" width="1200" height="750" on_scroll="true" gamepad_selectable="false" snap="false">
\t\t\t\t<options_scrollbar />
\t\t\t\t<scrollview clippingsoftness="0,10" anchor_top="#parent,1,0" anchor_bottom="buttons,1,10">
\t\t\t\t\t<grid pos="8,-20" cols="1" cell_width="700" cell_height="45" repeat_content="false" arrangement="horizontal" >
{combos}
\t\t\t\t\t</grid>
\t\t\t\t</scrollview>
\t\t\t</rect>
\t\t</rect>
\t</append>
</configs>
'''
os.makedirs(os.path.join(root, 'Config', 'XUi_Menu'), exist_ok=True)
with open(os.path.join(root, 'Config', 'XUi_Menu', 'windows.xml'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(xml)
print(f'options: {len(keys)} rows, {len(entries)} texts x {len(langs)} languages')
